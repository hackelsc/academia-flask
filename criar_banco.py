import os
import psycopg
from dotenv import load_dotenv
from werkzeug.security import generate_password_hash

load_dotenv()
senha_admin = os.environ["ADMIN_SENHA"]
conexao = psycopg.connect(os.environ["DATABASE_URL"])
cursor = conexao.cursor()

cursor.execute("""
    CREATE TABLE IF NOT EXISTS alunos (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        numero_matricula TEXT,
        nome TEXT,
        cpf TEXT UNIQUE,
        telefone TEXT,
        email TEXT,
        rua TEXT,
        numero TEXT,
        complemento TEXT,
        bairro TEXT,
        cidade TEXT,
        uf TEXT,
        cep TEXT,
        nascimento TEXT,
        mensalidade NUMERIC(10,2),
        dia_vencimento INTEGER,
        data_matricula TEXT,
        status INTEGER DEFAULT 1
    )
""")

cursor.execute("""
    CREATE TABLE IF NOT EXISTS funcionarios (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        nome TEXT,
        cpf TEXT UNIQUE,
        telefone TEXT,
        email TEXT,
        cargo TEXT,
        rua TEXT,
        numero TEXT,
        complemento TEXT,
        bairro TEXT,
        cidade TEXT,
        uf TEXT,
        cep TEXT,
        data_nascimento TEXT,
        data_admissao TEXT,
        status INTEGER DEFAULT 1
    )
""")

cursor.execute("""
    CREATE TABLE IF NOT EXISTS modalidades (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        nome TEXT
    )
""")

cursor.execute("""
    CREATE TABLE IF NOT EXISTS turmas (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        modalidade_id INTEGER,
        funcionario_id INTEGER,
        dia_semana TEXT,
        horario_inicio TEXT,
        horario_fim TEXT,
        status INTEGER DEFAULT 1,
        FOREIGN KEY (modalidade_id) REFERENCES modalidades (id),
        FOREIGN KEY (funcionario_id) REFERENCES funcionarios (id)
    )
""")

cursor.execute("""
    CREATE TABLE IF NOT EXISTS matriculas (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        turma_id INTEGER,
        aluno_id INTEGER,
        FOREIGN KEY (turma_id) REFERENCES turmas (id),
        FOREIGN KEY (aluno_id) REFERENCES alunos (id) ON DELETE CASCADE
    )
""")

cursor.execute("""
    CREATE TABLE IF NOT EXISTS pagamentos (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        aluno_id INTEGER,
        mes_referencia TEXT,
        valor NUMERIC(10,2),
        data_pagamento TEXT,
        forma_pagamento TEXT,
        status TEXT,
        FOREIGN KEY (aluno_id) REFERENCES alunos (id)
    )
""")

cursor.execute("""
    CREATE TABLE IF NOT EXISTS usuarios (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        nome TEXT,
        login TEXT UNIQUE,
        senha_hash TEXT,
        perfil TEXT
    )
""")
senha_hash_admin = generate_password_hash(senha_admin)
cursor.execute(
    "INSERT INTO usuarios (nome, login, senha_hash, perfil) VALUES (%s, %s, %s, %s) ON CONFLICT (login) DO NOTHING",
    ("Administrador", "admin@academia.com", senha_hash_admin, "admin")
)

conexao.commit()
conexao.close()

print("Banco de dados criado com sucesso!")
